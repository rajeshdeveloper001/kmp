#!/usr/bin/env python3
"""Writes VPlayed's `L10nKey` / `L10nPluralKey` (Swift) from the shared string catalog, so Swift code
names catalog keys with checked identifiers.

Usage: scripts/generate-swift-l10n-keys.py [output.swift]
Default output: ../VPlayed/VPlayed/Core/Localization/L10nKey.swift (relative to the kmp folder).
Run it after adding, renaming or removing keys in shared/src/commonMain/composeResources/values/strings.xml.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

KMP = Path(__file__).resolve().parent.parent
CATALOG = KMP / "shared/src/commonMain/composeResources/values/strings.xml"
OUTPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else KMP.parent / "VPlayed/VPlayed/Core/Localization/L10nKey.swift"


def camel(key: str) -> str:
    head, *rest = key.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


root = ET.parse(CATALOG).getroot()
strings = [(el.get("name"), "".join(el.itertext())) for el in root if el.tag == "string"]
plurals = [el.get("name") for el in root if el.tag == "plurals"]


def case_lines(items):
    lines = []
    for key, english in items:
        comment = " ".join(english.split())
        if len(comment) > 90:
            comment = comment[:87] + "…"
        lines.append(f"    /// {comment}" if comment else "")
        lines.append(f'    case {camel(key)} = "{key}"')
    return "\n".join(line for line in lines if line)


swift = f"""// Generated by kmp/scripts/generate-swift-l10n-keys.py from the shared string catalog
// (kmp/shared/src/commonMain/composeResources/values/strings.xml). Do not edit; run the script.

/// A string in the shared catalog. The comment is its English text.
nonisolated enum L10nKey: String, CaseIterable, Sendable {{
{case_lines(strings)}
}}

/// A plural string in the shared catalog.
nonisolated enum L10nPluralKey: String, CaseIterable, Sendable {{
{chr(10).join(f'    case {camel(key)} = "{key}"' for key in plurals)}
}}
"""
OUTPUT.write_text(swift)
print(f"{OUTPUT}: {len(strings)} strings, {len(plurals)} plurals")
